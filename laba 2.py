import numpy as np

# 1. Створюємо одновимірний масив з 200 випадкових чисел від -100 до 100
# Використовуємо randint (верхня межа 101, щоб число 100 було включно)
array = np.random.randint(-100, 101, size=200)
print("Початковий масив (перші 10 елементів):")
print(array[:10])

# 2. Використовуючи маску, фільтруємо всі додатні числа
# Маска — це масив логічних значень (True/False)
positive_mask = array > 0
positive_numbers = array[positive_mask]
print("\nДодатні числа (перші 10):")
print(positive_numbers[:10])

# 3. Замінюємо всі від’ємні значення на нулі
# Створюємо маску для від'ємних чисел і присвоюємо їм 0
array[array < 0] = 0
print("\nМасив після заміни від'ємних чисел на нулі (перші 10):")
print(array[:10])

# 4. Обчислюємо середнє значення отриманого масиву
average_value = np.mean(array)
print(f"\nСереднє значення масиву: {average_value}")